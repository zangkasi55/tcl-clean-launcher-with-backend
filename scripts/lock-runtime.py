"""Pin the installed runtime dependency graph for the Linux Python 3.12 image."""
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

environment = default_environment()
environment.update(sys_platform="linux", os_name="posix", platform_system="Linux",
                   python_version="3.12", python_full_version="3.12.12", extra="")
pending = [Requirement(item) for item in metadata.requires("tcl-tv-control") or []]
versions = {}
while pending:
    requirement = pending.pop()
    if requirement.marker and not requirement.marker.evaluate(environment):
        continue
    name = requirement.name.lower().replace("_", "-")
    if name in versions:
        continue
    distribution = metadata.distribution(name)
    if distribution.version not in requirement.specifier:
        raise RuntimeError(f"Installed dependency does not satisfy {requirement}")
    versions[name] = distribution.version
    pending.extend(Requirement(item) for item in distribution.requires or [])
target = Path(__file__).resolve().parents[1] / "controller" / "requirements.lock"
target.write_text("# Generated by scripts/lock-runtime.py; Linux CPython 3.12 runtime only.\n"
                  + "".join(f"{name}=={version}\n" for name, version in sorted(versions.items())),
                  encoding="utf-8")
print(f"Pinned {len(versions)} runtime dependencies to {target}")
